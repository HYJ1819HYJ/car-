#!/usr/bin/env python3
"""Export a conservative convex XY footprint from a binary or ASCII STL.

This is an offline geometry tool. It never accesses ROS or commands hardware.
The caller must establish CAD units, forward direction and the drive-axis origin.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import struct

import numpy as np
from scipy.spatial import ConvexHull, HalfspaceIntersection
import yaml


def read_stl(path):
    data = path.read_bytes()
    count = struct.unpack_from('<I', data, 80)[0] if len(data) >= 84 else 0
    if count and len(data) == 84 + 50*count:
        dtype = np.dtype([('normal', '<f4', (3,)), ('v', '<f4', (3, 3)),
                          ('attribute', '<u2')])
        points = np.frombuffer(data, dtype=dtype, count=count, offset=84)['v']
        points = points.reshape(-1, 3).astype(float)
    else:
        text = data.decode('ascii')
        number = r'([-+0-9.eE]+)'
        matches = re.findall(r'\bvertex\s+'+number+r'\s+'+number+r'\s+'+number, text)
        points = np.asarray(matches, dtype=float)
        if points.ndim != 2 or points.shape[1] != 3 or len(points) % 3:
            raise ValueError('Invalid ASCII STL vertices')
    if not len(points) or not np.isfinite(points).all():
        raise ValueError('STL has no finite vertices')
    return points


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('stl', type=Path)
    parser.add_argument('--units', choices=['mm', 'm'], required=True)
    parser.add_argument('--origin-xy', nargs=2, type=float, required=True,
                        help='Drive-axis midpoint in original CAD units')
    parser.add_argument('--support-directions', type=int, default=24)
    parser.add_argument('--output-yaml', type=Path, required=True)
    parser.add_argument('--output-json', type=Path, required=True)
    args = parser.parse_args()
    if args.support_directions < 8 or args.support_directions > 64 or args.support_directions % 4:
        parser.error('Support directions must be a multiple of four, from 8 to 64')
    points = read_stl(args.stl)
    scale = .001 if args.units == 'mm' else 1.
    xy = (points[:, :2]-np.asarray(args.origin_xy))*scale
    hull = ConvexHull(xy)
    angles = np.arange(args.support_directions)*2*math.pi/args.support_directions
    normals = np.c_[np.cos(angles), np.sin(angles)]
    # Intersect supporting halfplanes, rather than dropping contour vertices:
    # the output encloses every input vertex even along curved wheel edges.
    supports = np.max(xy @ normals.T, axis=0)+1e-6
    if np.any(supports <= 1e-9):
        parser.error('Drive-axis origin must be strictly inside the model footprint')
    vertices = HalfspaceIntersection(np.c_[normals, -supports], np.zeros(2)).intersections
    vertices = np.round(vertices[ConvexHull(vertices).vertices], 9)
    for a, b in zip(vertices, np.roll(vertices, -1, axis=0)):
        cross = (b[0]-a[0])*(xy[:, 1]-a[1])-(b[1]-a[1])*(xy[:, 0]-a[0])
        if cross.min() < -1e-8:
            raise ValueError('Simplified polygon does not enclose the entire model')
    polygon = vertices.tolist()
    bounds = {'vehicle_front_x': float(vertices[:, 0].max()),
              'vehicle_rear_x': float(vertices[:, 0].min()),
              'vehicle_half_width': float(np.abs(vertices[:, 1]).max())}
    document = {
        'robot_geometry': {'footprint': polygon, 'source_model': args.stl.name,
                           'scale_m_per_model_unit': scale,
                           'model_origin_xy': args.origin_xy},
        'serial_bridge': {'footprint': polygon, **bounds},
        'scan_self_filter': {'footprint': polygon, **bounds},
        'move_base': {
            'global_costmap': {'footprint': polygon},
            'local_costmap': {'footprint': polygon},
        },
    }
    report = {'source': str(args.stl), 'sha256': hashlib.sha256(args.stl.read_bytes()).hexdigest(),
              'units': args.units, 'model_origin_xy': args.origin_xy,
              'mapping': 'base X=(CAD X-origin X)*scale, base Y=(CAD Y-origin Y)*scale',
              'bounds_model_units': [points.min(axis=0).tolist(), points.max(axis=0).tolist()],
              'vertices_m': polygon, 'bounds_base_m': bounds,
              'full_projection_hull_area_m2': float(hull.volume),
              'exported_area_m2': float(ConvexHull(vertices).volume),
              'encloses_all_stl_vertices': True}
    for path in [args.output_yaml, args.output_json]:
        path.parent.mkdir(parents=True, exist_ok=True)
    args.output_yaml.write_text('# Generated by tools/stl_to_footprint.py; units are metres.\n'
                               +yaml.safe_dump(document, allow_unicode=True, sort_keys=False))
    args.output_json.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps({k: report[k] for k in ['bounds_base_m', 'encloses_all_stl_vertices',
                                           'full_projection_hull_area_m2', 'exported_area_m2']}, indent=2))


if __name__ == '__main__':
    main()
