#!/usr/bin/env python3
"""Reconstruct the supplied schematic; geometry remains editable in image pixels.

The start/finish yellow squares measure 74 x 73 pixels at their centre lines.
Both represent 0.8 x 0.8 m. Red annotations, blue target and black floor lines
are excluded from occupancy. This is a schematic map, not a surveyed SLAM map.
"""
import hashlib
import json
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
import yaml

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / 'src/competition_sim'
SX, SY = 0.8 / 74, 0.8 / 73
RES, MARGIN, WALL = 0.025, 0.3, 0.04
OUTLINE = [(9, 674), (823, 674), (823, 7), (437, 7), (437, 398), (9, 398)]
WALLS = [[(648, 146), (823, 146)], [(437, 398), (495, 488), (630, 488)],
         [(413, 605), (413, 674)]]
BOXES = [(461, 212, 529, 271), (697, 283, 765, 341),
         (300, 587, 367, 645), (702, 587, 769, 645)]


def xy(p):
    return [(p[0] - 9) * SX, (674 - p[1]) * SY]


def main():
    width = math.ceil((814 * SX + 2 * MARGIN) / RES)
    height = math.ceil((667 * SY + 2 * MARGIN) / RES)
    def pixel(p):
        x, y = xy(p)
        return (round((x + MARGIN) / RES - 0.5),
                height - 1 - round((y + MARGIN) / RES - 0.5))
    occupancy = Image.new('L', (width, height), 205)
    draw = ImageDraw.Draw(occupancy)
    draw.polygon([pixel(p) for p in OUTLINE], fill=254)
    stroke = max(1, math.ceil(WALL / RES))
    draw.line([pixel(p) for p in OUTLINE + OUTLINE[:1]], fill=0, width=stroke)
    for wall in WALLS:
        draw.line([pixel(p) for p in wall], fill=0, width=stroke)
    for x0, y0, x1, y1 in BOXES:
        draw.rectangle([pixel((x0, y0)), pixel((x1, y1))], fill=0)
    directory = PKG / 'maps'
    occupancy.save(directory / 'final_competition.pgm')
    # Stage uses binary occupancy, with unknown space solid as well.
    Image.fromarray(np.where(np.asarray(occupancy) == 254, 255, 0).astype('uint8')).save(
        directory / 'final_competition_stage.png')
    (directory / 'final_competition.yaml').write_text(yaml.safe_dump({
        'image': 'final_competition.pgm', 'resolution': RES,
        'origin': [-MARGIN, -MARGIN, 0.0], 'negate': 0,
        'occupied_thresh': 0.65, 'free_thresh': 0.196}, sort_keys=False))
    start = xy((616, 42.5)) + [-math.pi / 2]
    finish = xy((46, 440.5)) + [math.pi]
    # Park wholly inside the 0.8 m square with clearance for the asymmetric
    # nose and the final safety stop, rather than aiming the nose at the wall.
    finish[0] += 0.10
    metadata = {
        'source_sha256': hashlib.sha256((directory / 'source_diagram.jpg').read_bytes()).hexdigest(),
        'calibration': {'yellow_square_m': 0.8, 'yellow_square_pixels': [74, 73],
                        'metres_per_pixel_xy': [SX, SY]},
        'outer_bounds_m': [814 * SX, 667 * SY], 'resolution_m': RES,
        'wall_thickness_assumed_m': WALL,
        'note': 'Schematic reconstruction. Dimensions/obstacle placement and wall thickness require field measurement. Raster wall width rounds up to 2 cells (0.05 m). Ground start/finish lines are not walls.',
        'outline_pixels': OUTLINE, 'wall_polylines_pixels': WALLS, 'box_rectangles_pixels': BOXES,
        'start': start, 'finish': finish,
        'start_square_m': [xy((579, 79)), xy((653, 6))],
        'finish_square_m': [xy((9, 477)), xy((83, 404))],
        'finish_is_movable': True,
    }
    (directory / 'geometry.json').write_text(json.dumps(metadata, indent=2) + '\n')
    preview = occupancy.convert('RGB').resize((width*3, height*3), Image.Resampling.NEAREST)
    pd = ImageDraw.Draw(preview)
    for rect, label in [(((579, 6), (653, 79)), 'START 0.8 m'),
                        (((9, 404), (83, 477)), 'FINISH 0.8 m')]:
        a, b = [tuple(v*3 for v in pixel(p)) for p in rect]
        pd.rectangle([a, b], outline='#e4b600', width=4)
        pd.text((a[0]+4, a[1]+6), label, fill='#ad5600')
    preview.save(directory / 'preview.png')
    footprint = yaml.safe_load((ROOT / 'src/maze_bridge/config/footprint_stl.yaml').read_text())['robot_geometry']['footprint']
    pts = np.asarray(footprint)
    bounds = pts.max(axis=0) - pts.min(axis=0)
    center = (pts.max(axis=0) + pts.min(axis=0)) / 2
    block = '\n'.join(f'      point[{i}] [{x:.9f} {y:.9f}]' for i, (x, y) in enumerate(pts))
    # Map size and centre use complete raster extents, including the margin.
    world = f'''# Generated by tools/generate_final_competition_map.py
resolution 0.0125
interval_sim 33
speedup 1
window( size [1000 850] center [4.4 3.65] scale 95 show_data 1 )
model(
  name "competition_field"
  bitmap "../maps/final_competition_stage.png"
  size [{width*RES:.6f} {height*RES:.6f} 0.60]
  pose [{width*RES/2-MARGIN:.6f} {height*RES/2-MARGIN:.6f} 0 0]
  boundary 0 gui_nose 0 gui_grid 0 gui_move 0
  color "gray30" obstacle_return 1 ranger_return 1
)
position(
  name "xiaoche" color "blue" gui_nose 1 gui_move 0
  update_interval 33
  size [{bounds[0]:.9f} {bounds[1]:.9f} 0.275228821]
  origin [{center[0]:.9f} {center[1]:.9f} 0 0]
  pose [{start[0]:.9f} {start[1]:.9f} 0 -90]
  drive "diff"
  localization "odom" localization_origin [0 0 0 0]
  odom_error [0.001 0.001 0 0.001]
  velocity_bounds [0 0.50 0 0 0 0 -42.971835 42.971835]
  acceleration_bounds [-0.50 0.50 0 0 0 0 -85.943669 85.943669]
  block(
    points {len(pts)}
{block}
    z [0 0.275228821]
  )
  ranger(
    pose [0.315 0 0.054771179 0]
    size [0.05 0.05 0.05] color "black"
    update_interval 33
    sensor( range [0.05 10.0] fov 360 samples 1440 )
  )
)
'''
    (PKG / 'worlds/final_competition.world').write_text(world)
    print(json.dumps({'bounds_m': metadata['outer_bounds_m'], 'start': start, 'finish': finish,
                      'raster_size': [width, height]}, indent=2))


if __name__ == '__main__':
    main()
